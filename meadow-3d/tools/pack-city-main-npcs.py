"""Publish the approved native AutoSprite city clips without per-frame warping."""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parents[2]
source = root / 'output/city-main-npc-video-v1'
public = root / 'meadow-3d/public/assets/city-painted-v1'
clips = {}
for name in ['merchant', 'blacksmith', 'clerk', 'healer', 'guard', 'angel', 'herbalist']:
    folder = source / name
    sheet_file, atlas_file = folder/'source.png', folder/'atlas.json'
    if name == 'herbalist':
        folder = root/'output/npc-herbalist-video-wave-v1'
        sheet_file, atlas_file = folder/'sprite-sheet.png', folder/'atlas.json'
    atlas = json.loads(atlas_file.read_text(encoding='utf-8'))
    sheet = Image.open(sheet_file).convert('RGBA')
    cells = [atlas['frames'][str(i)] for i in range(len(atlas['frames']))]
    first = cells[0]
    frame = sheet.crop((first['x'], first['y'], first['x']+first['w'], first['y']+first['h']))
    bounds = frame.getchannel('A').getbbox()
    assert bounds and len(cells) == 32
    assert all(c['w'] == first['w'] and c['h'] == first['h'] for c in cells)
    columns = sheet.width // first['w']
    for i, cell in enumerate(cells):
        assert (cell['x'], cell['y']) == (i % columns * first['w'], i // columns * first['h'])
    # Human crown-to-foot height matches the player; spear/wings do not set body scale.
    # Guard crown y=73 was read on source frame 0; the spear tip starts at y=2.
    if name == 'guard':
        bounds = (bounds[0],73,bounds[2],bounds[3])
    height = 1.8
    filename = 'herbalist-wave-v1.webp' if name == 'herbalist' else f'{name}-idle-video-v1.webp'
    # A 256 px cell covers the game's normal/zoomed NPCs without seven 3072 px decoded atlases.
    # Resize the complete atlas once; preserve every frame's relative geometry and anchor.
    runtime_scale = 256/first['h']
    runtime_cell = [round(first['w']*runtime_scale),256]
    runtime = sheet.resize((round(sheet.width*runtime_scale),round(sheet.height*runtime_scale)),Image.Resampling.LANCZOS)
    runtime.save(public/filename, format='WEBP', quality=92, method=6)
    clips[name] = {'file': '/assets/city-painted-v1/'+filename, 'cell': runtime_cell,
                   'columns': columns, 'frames': len(cells), 'duration': atlas['meta']['duration_s'],
                   'bodyBounds': [v*runtime_scale for v in bounds], 'worldHeight': height}
    durations = [round((i+1)*clips[name]['duration']/len(cells)*100)*10-round(i*clips[name]['duration']/len(cells)*100)*10 for i in range(len(cells))]
    preview = []
    for cell in cells:
        image = sheet.crop((cell['x'],cell['y'],cell['x']+cell['w'],cell['y']+cell['h']))
        bg = Image.new('RGB', image.size, '#e4e0d5')
        bg.paste(image,(0,0),image)
        preview.append(bg)
    preview[0].save(folder/'preview.gif',save_all=True,append_images=preview[1:],duration=durations,loop=0)
    print(name, bounds, clips[name]['duration'], (public/filename).stat().st_size)

(root/'meadow-3d/src/city-npc-clips.ts').write_text(
    '// Generated by tools/pack-city-main-npcs.py from approved native video atlases.\n'
    'export const CITY_NPC_CLIPS = '+json.dumps(clips,indent=2)+' as const;\n',encoding='utf-8')
(source/'runtime-clips.json').write_text(json.dumps(clips,indent=2),encoding='utf-8')
