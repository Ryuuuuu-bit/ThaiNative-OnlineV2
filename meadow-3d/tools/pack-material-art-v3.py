"""Normalize the retained original material icons and publish their runtime registry."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'meadow-3d/art/item-art-v3'
OUT = ROOT / 'meadow-3d/public/assets/item-art-v3'


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pack():
    plan = read(ART / 'plan.json')['items']
    items = {i['id']: i for i in read(ROOT / 'shared/data/items.json')['items']}
    assert len(plan) == 100 and len({i['id'] for i in plan}) == 100
    OUT.mkdir(parents=True, exist_ok=True)
    files = []
    for entry in plan:
        name = entry['id']
        source = ART / 'originals' / f'{name}.png'
        receipt = ART / 'originals' / f'{name}.receipt.json'
        provenance = read(receipt)
        assert provenance['provider'] == 'built-in image_gen'
        assert provenance['transparent_background'] is True
        assert items[name]['type'] in ['material', 'consumable']
        with Image.open(source) as raw:
            assert raw.mode == 'RGBA' and raw.getchannel('A').getextrema()[0] == 0, name
            alpha = raw.getchannel('A')
            bounds = alpha.point(lambda a: 255 if a >= 32 else 0).getbbox()
            assert bounds, name
            x, y, r, b = bounds
            assert x > 0 and y > 0 and r < raw.width and b < raw.height, (name, 'source touches canvas edge')
            crop = raw.crop((max(0, x-4), max(0, y-4), min(raw.width, r+4), min(raw.height, b+4)))
            crop.thumbnail((176, 176), Image.Resampling.LANCZOS)
            icon = Image.new('RGBA', (192, 192))
            icon.paste(crop, ((192-crop.width)//2, (192-crop.height)//2))
        target = OUT / f'{name}.png'
        icon.save(target, optimize=True)
        box = icon.getchannel('A').getbbox()
        assert box and box[0] >= 8 and box[1] >= 8 and box[2] <= 184 and box[3] <= 184, name
        files.append({'id': name, 'file': target.name, 'kind': items[name]['type'],
                      'sha256': digest(target), 'source': source.relative_to(ROOT).as_posix(),
                      'sourceSha256': digest(source), 'sourceReceipt': receipt.relative_to(ROOT).as_posix(),
                      'receiptSha256': digest(receipt), 'canvas': [192, 192], 'bounds': box,
                      'sourceBounds': bounds, 'clippedPixels': 0, 'bytes': target.stat().st_size})
    manifest = {'version': 3, 'method': 'Original individual built-in image_gen paintings, native alpha, deterministic crop and contain fit.',
                'externalReferences': [], 'files': files}
    (OUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    registry = {f['id']: f['file'] for f in files}
    (ROOT / 'meadow-3d/src/material-art-data.ts').write_text(
        '// Generated by tools/pack-material-art-v3.py.\nexport const MATERIAL_ITEM_ART:Readonly<Record<string,string>>='
        +json.dumps(registry, indent=1)+';\n', encoding='utf-8')
    preview = Image.new('RGB', (10*144, 10*162), '#162b27')
    draw = ImageDraw.Draw(preview)
    for n, entry in enumerate(files):
        x, y = n % 10*144, n//10*162
        draw.rounded_rectangle((x+5, y+5, x+139, y+139), 8, fill='#284137', outline='#607a65')
        with Image.open(OUT / entry['file']) as icon:
            icon.thumbnail((112, 112))
            preview.paste(icon, (x+(144-icon.width)//2, y+14), icon)
        draw.text((x+6, y+143), entry['id'][:24], fill='#dbd5b0', font_size=9)
    qa = ART / 'qa'
    qa.mkdir(exist_ok=True)
    preview.save(qa / 'contact.jpg', quality=92)
    print(f'Published {len(files)} icons: {sum(f["kind"] == "material" for f in files)} materials, {sum(f["kind"] == "consumable" for f in files)} consumables')


if __name__ == '__main__':
    pack()
