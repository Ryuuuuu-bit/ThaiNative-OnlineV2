"""Publish the approved Sprite-Gen static cuts and original card frames; no generation."""
from pathlib import Path
from PIL import Image,ImageDraw
import hashlib,json
root=Path(__file__).resolve().parents[2];art=root/'meadow-3d/art/item-art-v2';public=root/'meadow-3d/public/assets/item-art-v2'
digest=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
files=json.loads((art/'cards.provenance.json').read_text(encoding='utf-8'))['files'];sheet_sources=[]
for n in range(1,6):
 sheet=art/f'sheet-{n}.png';receipt=art/f'sheet-{n}.receipt.json';generation=json.loads(receipt.read_text(encoding='utf-8'))
 assert generation['provider']=='codex'and generation['refs']==[]
 cuts=art/f'cuts-{n}';report=json.loads((cuts/'slice-sheet.json').read_text(encoding='utf-8'))
 assert report['grid']==[4,4]and report['fit']=='contain'
 sheet_sources.append({'source':sheet.relative_to(root).as_posix(),'sha256':digest(sheet),'receipt':receipt.relative_to(root).as_posix(),'receiptSha256':digest(receipt)})
 for cell in report['cells']:
  assert cell['clipped_px']==0,cell['name']
  source=cuts/cell['file'];cut=Image.open(source).convert('RGBA');assert cut.size==(192,192)
  im=Image.new('RGBA',(192,192));im.paste(cut.resize((176,176),Image.Resampling.LANCZOS),(8,8))
  box=im.getbbox();assert box and box[0]>0 and box[1]>0 and box[2]<192 and box[3]<192,(source,box)
  target=public/source.name;im.save(target,optimize=True)
  id=cell['name'];kind='unique'if id.startswith('unique_')else'gear'if id.startswith('field_')else'material'
  files.append({'id':id,'file':target.name,'kind':kind,'sha256':digest(target),'source':sheet.relative_to(root).as_posix(),'sourceSha256':digest(sheet),'sourceReceipt':receipt.relative_to(root).as_posix(),'canvas':[192,192],'bounds':box,'clippedPixels':0,'bytes':target.stat().st_size})
assert len(files)==191 and len({f['id']for f in files})==191
manifest={'version':2,'method':'Original GPT artwork through Sprite-Gen native alpha and canonical static-sheet slicing. Cards use verified existing original monster bases inside newly authored vector frames.','externalReferences':[],'sources':sheet_sources,'files':files}
(public/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(root/'meadow-3d/src/item-art-data.ts').write_text('// Generated by tools/pack-item-art-v2.py. Canonical item icon overrides.\nexport const PAINTED_ITEM_ART:Readonly<Record<string,string>>='+json.dumps({f['id']:f['file']for f in files},indent=1)+';\n',encoding='utf-8')
# Native-size evidence on a game-like dark inventory background.
contact=Image.new('RGB',(10*144,8*188),'#162b27');draw=ImageDraw.Draw(contact)
icons=[f for f in files if f['kind']!='card']
for i,f in enumerate(icons):
 x=i%10*144;y=i//10*188;draw.rounded_rectangle((x+5,y+5,x+139,y+139),8,fill='#284137',outline='#607a65');im=Image.open(public/f['file']);im.thumbnail((112,112));contact.paste(im,(x+(144-im.width)//2,y+14),im);draw.text((x+6,y+145),f['id'].replace('field_','')[:22],fill='#dbd5b0')
contact.save(art/'icons-contact.jpg',quality=88)
print('Published 191 icons:',{kind:sum(f['kind']==kind for f in files)for kind in ['gear','unique','material','card']})
