"""Normalize the 208 original class item illustrations and publish their exact-ID mapping."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / 'meadow-3d/art/class-items-v1'
PUBLIC = ROOT / 'meadow-3d/public/assets/class-items-v1'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    catalog = json.loads((ART / 'catalog.json').read_text(encoding='utf-8-sig'))
    assert len(catalog) == 208 and len({i['id'] for i in catalog}) == 208
    PUBLIC.mkdir(parents=True, exist_ok=True)
    records = []
    prompts = []
    for item in catalog:
        identity = item['id']
        source = ART / 'sources' / f'{identity}.png'
        receipt_path = source.with_suffix('.receipt.json')
        receipt = json.loads(receipt_path.read_text(encoding='utf-8-sig'))
        assert receipt['id'] == identity and receipt['provider'] == 'image_gen'
        assert receipt['transparentRequested'] is True
        prompts.append({'id': identity, 'prompt': receipt['prompt'], 'reference': receipt.get('reference')})
        image = Image.open(source).convert('RGBA')
        alpha = image.getchannel('A')
        assert alpha.getextrema()[0] == 0, f'{identity}: missing transparency'
        bounds = alpha.point(lambda x: 255 if x > 8 else 0).getbbox()
        assert bounds and min(bounds[2] - bounds[0], bounds[3] - bounds[1]) > 30, identity
        assert bounds[0] > 0 and bounds[1] > 0 and bounds[2] < image.width and bounds[3] < image.height, f'{identity}: source clipped at canvas edge'
        cut = image.crop(bounds)
        cut.thumbnail((176, 176), Image.Resampling.LANCZOS)
        icon = Image.new('RGBA', (192, 192))
        icon.alpha_composite(cut, ((192 - cut.width) // 2, (192 - cut.height) // 2))
        bounds = icon.getbbox()
        assert bounds and min(bounds[0], bounds[1]) >= 8 and max(bounds[2], bounds[3]) <= 184, identity
        target = PUBLIC / f'{identity}.png'
        icon.save(target, optimize=True)
        records.append({
            'id': identity, 'nameTh': item['nameTh'], 'file': target.name,
            'kind': 'unique' if identity.startswith('unique_') else 'gear',
            'sha256': digest(target), 'bytes': target.stat().st_size,
            'source': source.relative_to(ROOT).as_posix(), 'sourceSha256': digest(source),
            'receipt': receipt_path.relative_to(ROOT).as_posix(), 'receiptSha256': digest(receipt_path),
            'canvas': [192, 192], 'bounds': bounds,
        })
    assert len({r['sha256'] for r in records}) == 208, 'Repeated artwork'
    assert sum(r['kind'] == 'unique' for r in records) == 7
    reference = ART / 'style-reference.jpg'
    manifest = {'version': 1, 'provider': 'image_gen', 'method': 'One original generation per item; alpha crop, contain, and center with 8px safe margin.', 'styleReference': {'source': reference.relative_to(ROOT).as_posix(), 'sha256': digest(reference)}, 'externalReferences': [], 'files': records}
    (PUBLIC / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    (ART / 'generation-prompts.json').write_text(json.dumps(prompts, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    mapping = {r['id']: r['file'] for r in records}
    (ROOT / 'meadow-3d/src/class-item-art-data.ts').write_text(
        '// Generated by tools/pack-class-item-art.py. One dedicated illustration per new class item.\n'
        + 'export const CLASS_ITEM_ART:Readonly<Record<string,string>>='
        + json.dumps(mapping, indent=1) + ';\n', encoding='utf-8')
    item_path = ROOT / 'shared/data/items.json'
    current = json.loads(item_path.read_text(encoding='utf-8-sig'))
    assert set(mapping).issubset({item['id'] for item in current['items']})
    for item in current['items']:
        if item['id'] in mapping:
            item['icon'] = item['id']
    item_path.write_text(json.dumps(current, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    for start in range(0, len(records), 32):
        group = records[start:start + 32]
        sheet = Image.new('RGB', (8 * 144, 4 * 172), '#162b27')
        draw = ImageDraw.Draw(sheet)
        for index, record in enumerate(group):
            x, y = index % 8 * 144, index // 8 * 172
            draw.rounded_rectangle((x + 5, y + 5, x + 139, y + 139), 8, fill='#284137', outline='#607a65')
            icon = Image.open(PUBLIC / record['file'])
            icon.thumbnail((112, 112), Image.Resampling.LANCZOS)
            sheet.paste(icon, (x + (144 - icon.width) // 2, y + 14), icon)
            draw.text((x + 5, y + 144), record['id'].replace('field_', '')[:23], fill='#dbd5b0')
        sheet.save(ART / f'preview-{start // 32 + 1}.jpg', quality=92)
    print(f'Published {len(records)} original icons ({sum(r["bytes"] for r in records):,} bytes).')


if __name__ == '__main__':
    main()
