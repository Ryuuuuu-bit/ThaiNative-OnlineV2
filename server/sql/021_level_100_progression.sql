-- During a rolling deploy an older server may still hold EXP in the old curve.
-- Reject its stale progress writes after conversion; current pools identify themselves at startup.
CREATE OR REPLACE FUNCTION tn2_guard_progression_writer() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.level IS DISTINCT FROM OLD.level OR NEW.xp IS DISTINCT FROM OLD.xp)
    AND current_setting('application_name', true) IS DISTINCT FROM 'tn2-progression-v2' THEN
  RAISE EXCEPTION 'Retired EXP writer; reconnect to the current game build' USING ERRCODE='40001';
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS tn2_progression_writer ON tn2_characters;
-- No UPDATE OF column dependency: the historical bigint migration is re-runnable.
CREATE TRIGGER tn2_progression_writer BEFORE UPDATE ON tn2_characters
 FOR EACH ROW EXECUTE FUNCTION tn2_guard_progression_writer();
